#!/usr/bin/env node

import fs from "node:fs/promises";
import path from "node:path";
import { spawn } from "node:child_process";
import { fileURLToPath } from "node:url";

const skillDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const templateDir = path.join(skillDir, "template");
const outDir = process.argv[2] ? path.resolve(process.argv[2]) : "";

if (!outDir) {
  console.error("Usage: node publish-dashboard.mjs <audit-out-dir>");
  process.exit(1);
}

const runDirs = (await fs.readdir(outDir, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory() && /^\d{4}-\d{2}-\d{2}(?:-\d{6}(?:-\d+)?)?$/.test(entry.name));
const results = await Promise.all(runDirs.map(async (entry) => {
  const file = path.join(outDir, entry.name, "results.json");
  try {
    await fs.access(file);
    return file;
  } catch {
    return null;
  }
}));
if (!results.some(Boolean)) throw new Error(`No completed dated results.json in ${outDir}`);

await new Promise((resolve, reject) => {
  const child = spawn("npm", ["run", "build"], {
    cwd: templateDir,
    env: { ...process.env, AUDIT_RUNS_DIR: outDir },
    stdio: "inherit",
  });
  child.on("error", reject);
  child.on("exit", (code) => code === 0 ? resolve() : reject(new Error(`Dashboard build exited ${code}`)));
});

const source = path.join(templateDir, "out");
const destination = path.join(outDir, "report");
const marker = ".geo-audit-dashboard";
let hasDestination = false;
try {
  await fs.access(destination);
  hasDestination = true;
} catch (error) {
  if (!error || typeof error !== "object" || !("code" in error) || error.code !== "ENOENT") throw error;
}
if (hasDestination) {
  try {
    await fs.access(path.join(destination, marker));
  } catch {
    throw new Error(`Existing ${destination} is not a managed dashboard; choose another audit directory`);
  }
}

const staging = path.join(outDir, `.report-next-${process.pid}`);
const previous = path.join(outDir, `.report-previous-${process.pid}`);
await fs.mkdir(staging);
try {
  await fs.copyFile(path.join(source, "index.html"), path.join(staging, "index.html"));
  await fs.cp(path.join(source, "_next"), path.join(staging, "_next"), { recursive: true });
  await fs.writeFile(path.join(staging, marker), "Generated by geo-audit-report/scripts/publish-dashboard.mjs\n");
  let hadPrevious = false;
  try {
    await fs.rename(destination, previous);
    hadPrevious = true;
  } catch (error) {
    if (!error || typeof error !== "object" || !("code" in error) || error.code !== "ENOENT") throw error;
  }
  try {
    await fs.rename(staging, destination);
  } catch (error) {
    if (hadPrevious) await fs.rename(previous, destination);
    throw error;
  }
  if (hadPrevious) await fs.rm(previous, { recursive: true });
} finally {
  await fs.rm(staging, { recursive: true, force: true });
}

console.log(path.join(destination, "index.html"));
